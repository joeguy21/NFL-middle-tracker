const assert=require("node:assert/strict");
const {nextPollDelay,MINUTE_MS,HOUR_MS}=require("./odds-poll-scheduler");
const now=Date.parse("2026-10-27T12:00:00Z");
const rec=(status,startTime,gameStatus)=>({recordType:"coordinated-game",status,gameStatus,event:{startTime}});
assert.equal(nextPollDelay([],now),HOUR_MS,"No tracked game: idle scheduler waits an hour; no odds calls.");
assert.equal(nextPollDelay([rec("stopped","2026-10-27T12:00:00Z")],now),HOUR_MS);
assert.equal(nextPollDelay([rec("tracking","2026-10-27T16:00:00Z")],now),HOUR_MS,"Far pregame status checks hourly.");
assert.equal(nextPollDelay([rec("tracking","2026-10-27T12:30:00Z")],now),MINUTE_MS,"Near kickoff: frequent status checks, but odds are separately gated hourly.");
assert.equal(nextPollDelay([rec("tracking","2026-10-27T11:00:00Z","in-progress")],now),MINUTE_MS,"Live game uses minute cycle.");
assert.equal(nextPollDelay([rec("tracking","bad")],now),HOUR_MS,"Unknown kickoff remains hourly, not high frequency.");
console.log("odds poll scheduler tests passed");
