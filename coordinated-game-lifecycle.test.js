const assert=require("node:assert/strict");
const {createCoordinatedGame,startTracking,stopTracking,acceptCoordinatedPlan,ignoreCoordinatedAlert}=require("./coordinated-game-lifecycle");
const event={league:"nfl",homeTeam:"Green Bay Packers",awayTeam:"Carolina Panthers",startTime:"2026-10-30T00:16:00Z"};
const legs=[
 {team:"A",teamName:"Carolina Panthers",spread:3.5,odds:-110,stake:100,sportsbook:"FanDuel"},
 {team:"B",teamName:"Green Bay Packers",spread:-3.5,odds:-110,stake:100,sportsbook:"DraftKings"}
];
const saved=createCoordinatedGame({id:"g-1",event,legs,createdAt:"2026-10-29T12:00:00Z"});
assert.equal(saved.status,"tracking","Successful save activates monitoring immediately.");
assert.equal(saved.trackingStartedAt,saved.createdAt);
assert.equal(saved.originalLegs.length,2);
assert.equal(saved.minimumMiddlePoints,3,"Default alert threshold is 3 points.");
const customThreshold=createCoordinatedGame({id:"g-custom",event,legs,minimumMiddlePoints:5});
assert.equal(customThreshold.minimumMiddlePoints,5);
assert.throws(()=>createCoordinatedGame({id:"g-invalid",event,legs,minimumMiddlePoints:-1}),/threshold must be between/);
assert.throws(()=>createCoordinatedGame({id:"g-invalid",event,legs,minimumMiddlePoints:21}),/threshold must be between/);
const active=startTracking(saved,{now:"2026-10-29T12:01:00Z"});
assert.equal(active.status,"tracking");
assert.equal(active.trackingStartedAt,saved.createdAt);
assert.equal(startTracking(active).status,"tracking");
const stopped=stopTracking(active,{now:"2026-10-29T12:03:00Z"});
assert.equal(stopped.status,"stopped");
assert.deepEqual(stopped.originalLegs,active.originalLegs);
assert.deepEqual(stopped.event,active.event);
assert.equal(stopped.id,active.id);
assert.equal(stopped.trackingStartedAt,active.trackingStartedAt);
assert.equal(stopped.stoppedAt,"2026-10-29T12:03:00Z");
assert.throws(()=>stopTracking(stopped),/Only active tracking/);
assert.throws(()=>createCoordinatedGame({id:"x",event,legs:[legs[0]]}),/valid original wagers/);
assert.throws(()=>createCoordinatedGame({id:"x",event,legs:[legs[0],{...legs[1],team:"A"}]}),/valid original wagers/);
assert.throws(()=>createCoordinatedGame({id:"x",event,legs:[legs[0],{...legs[1],odds:0}]}),/valid original wagers/);
assert.throws(()=>startTracking({...saved,status:"stopped"}),/Only saved games/);
assert.equal(stopTracking(saved,{now:"2026-10-29T12:03:00Z"}).status,"stopped");
assert.throws(()=>createCoordinatedGame({id:"x",event,legs:[legs[0],{...legs[1],teamName:"Chicago Bears"}]}),/match a different team/);
assert.throws(()=>createCoordinatedGame({id:"x",event:{...event,homeTeam:"Carolina Panthers"},legs}),/valid ID and scheduled/);
assert.throws(()=>createCoordinatedGame({id:"x",event:{...event,league:"mlb"},legs}),/valid ID and scheduled/);
assert.throws(()=>createCoordinatedGame({id:"x",event:{...event,startTime:"not-a-date"},legs}),/valid ID and scheduled/);
assert.equal(createCoordinatedGame({id:" x ",event,legs}).id,"x");
const accepted=acceptCoordinatedPlan(saved,{planId:"recommendation-7",now:"2026-10-29T12:05:00Z"});
assert.equal(accepted.status,"stopped","Accepting recommendation stops tracking this set.");
assert.equal(accepted.acceptedPlanId,"recommendation-7");
assert.equal(accepted.acceptedAt,"2026-10-29T12:05:00Z");
assert.equal(saved.status,"tracking","Pure transition does not mutate source; adapter must persist accepted result.");
assert.throws(()=>acceptCoordinatedPlan(accepted,{planId:"again"}),/actively tracked/);
const ignored=ignoreCoordinatedAlert(saved);
assert.equal(ignored.status,"tracking","Ignoring keeps the wager set active.");
assert.equal(ignored.stoppedAt,null);
assert.equal(ignoreCoordinatedAlert(ignored).status,"tracking","Repeated alerts remain eligible.");
assert.throws(()=>ignoreCoordinatedAlert(accepted),/actively tracked/);
assert.throws(()=>acceptCoordinatedPlan(saved,{}),/plan ID is required/);
console.log("coordinated game lifecycle tests passed");
